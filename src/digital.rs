//! Checked DLT3 stereo track descriptors shared by the baker and DAC backend.
//!
//! The stereo extension retains the 32-byte little-endian header and uses
//! 521 pairs of sixteen three-byte signed-magnitude deltas. Each stream byte
//! holds one frame: left in the low nibble, right in the high nibble.
//! H.A.V.O.C. appends the source player's cumulative
//! CRC-8 after each 1024 stream bytes (including the final short chunk).
//! Exact shipping metadata binds the decoder to the checked-in asset.

pub const REU_SIZE: u32 = 0x1000000;
pub const GALACTIC_OFFSET: u32 = 0x100000;
pub const HAMMOND_OFFSET: u32 = 0x500000;
/// Legacy Galactic Dash asset offset.
pub const ASSET_OFFSET: u32 = GALACTIC_OFFSET;
pub const RING_OFFSET: u32 = 0xfe0000;
pub const RING_BYTES: u32 = 0x20000;
pub const HEADER_SIZE: usize = 32;
pub const SAMPLE_RATE: u32 = 24_000;
pub const BITS_PER_SAMPLE: u8 = 4;
pub const CHANNELS: u8 = 2;
pub const CODEBOOK_ENTRIES: usize = 16;
pub const CODEBOOK_BYTES: usize = CODEBOOK_ENTRIES * 3 * CHANNELS as usize;
pub const CODEBOOK_COUNT: u16 = 521;
pub const CRC_CHUNK_BYTES: usize = 1024;

// Generated by tools/encode-digital-music; see assets/music/galactic-dash.json.
pub const SAMPLE_COUNT: u32 = 3_685_440;
pub const SAMPLES_PER_SEGMENT: u32 = 7_072;
pub const STREAM_BYTES: u32 = SAMPLE_COUNT;
pub const STREAM_OFFSET: u32 = 50_048;
pub const CRC_OFFSET: u32 = 3_735_488;
pub const CRC_COUNT: usize = 3_600;
// REU extents must stay u32: the MOS target has a sixteen-bit usize.
pub const ASSET_BYTES: u32 = 3_739_088;
pub const HEADER_CHECKSUM: u16 = 63_424;
pub const CODEBOOK_CHECKSUM: u16 = 39_876;
pub const CRC_TABLE_CHECKSUM: u16 = 43_724;
pub const ASSET_CHECKSUM: u16 = 16_726;

const _: () = assert!(ASSET_OFFSET + ASSET_BYTES <= HAMMOND_OFFSET);
const _: () = assert!(RING_OFFSET + RING_BYTES == REU_SIZE);
const _: () =
    assert!(STREAM_OFFSET == HEADER_SIZE as u32 + CODEBOOK_COUNT as u32 * CODEBOOK_BYTES as u32);
const _: () = assert!(STREAM_BYTES == SAMPLE_COUNT);
const _: () = assert!(CRC_OFFSET == STREAM_OFFSET + STREAM_BYTES);
const _: () = assert!(CRC_COUNT as u32 == (STREAM_BYTES + 1023) / 1024);
const _: () = assert!(ASSET_BYTES == CRC_OFFSET + CRC_COUNT as u32);

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
#[repr(C)]
pub struct Metadata {
    /// Stereo frames (one sample per channel), not interleaved scalar samples.
    pub total_samples: u32,
    pub stream_bytes: u32,
    /// Stereo frames sharing one pair of codebooks.
    pub samples_per_segment: u32,
    /// Offsets are relative to the selected asset, not absolute REU addresses.
    pub stream_offset: u32,
    pub crc_offset: u32,
    pub codebook_count: u16,
}

impl Metadata {
    pub const EMPTY: Self = Self {
        total_samples: 0,
        stream_bytes: 0,
        samples_per_segment: 0,
        stream_offset: 0,
        crc_offset: 0,
        codebook_count: 0,
    };
}

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
#[repr(u8)]
pub enum Track {
    #[default]
    GalacticDash = 0,
    HammondRocker = 1,
}

impl Track {
    #[inline(always)]
    pub fn descriptor(self) -> &'static Descriptor {
        descriptor(self)
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[repr(C)]
pub struct Descriptor {
    pub asset_offset: u32,
    pub asset_bytes: u32,
    pub header_checksum: u16,
    pub codebook_checksum: u16,
    pub crc_table_checksum: u16,
    pub asset_checksum: u16,
    pub metadata: Metadata,
}

const GALACTIC_DESCRIPTOR: Descriptor = Descriptor {
    asset_offset: GALACTIC_OFFSET,
    asset_bytes: ASSET_BYTES,
    header_checksum: HEADER_CHECKSUM,
    codebook_checksum: CODEBOOK_CHECKSUM,
    crc_table_checksum: CRC_TABLE_CHECKSUM,
    asset_checksum: ASSET_CHECKSUM,
    metadata: Metadata {
        total_samples: SAMPLE_COUNT,
        stream_bytes: STREAM_BYTES,
        samples_per_segment: SAMPLES_PER_SEGMENT,
        stream_offset: STREAM_OFFSET,
        crc_offset: CRC_OFFSET,
        codebook_count: CODEBOOK_COUNT,
    },
};

